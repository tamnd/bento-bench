package bench

import (
	"context"
	"os"
	"path/filepath"
	"runtime"
	"testing"
)

// stubBento writes a small executable that prints a fixed body to stdout, so the
// golden emitter can be exercised without a real bento on the machine. The body
// is what a caller checks lands in the .golden file.
func stubBento(t *testing.T, body string) string {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("stub bento uses a POSIX shell script")
	}
	dir := t.TempDir()
	path := filepath.Join(dir, "bento")
	script := "#!/bin/sh\nprintf '%s' " + shellQuote(body) + "\n"
	if err := os.WriteFile(path, []byte(script), 0o755); err != nil {
		t.Fatalf("write stub: %v", err)
	}
	return path
}

// shellQuote wraps s in single quotes for the stub script, which only ever
// carries plain generated-Go text with no single quotes of its own.
func shellQuote(s string) string { return "'" + s + "'" }

func TestEmitGoldenWritesThenSkipsUnchanged(t *testing.T) {
	body := "// Code generated by bento test (commit none) from w.ts. DO NOT EDIT.\n\npackage main\n"
	bento := stubBento(t, body)

	work := t.TempDir()
	tsPath := filepath.Join(work, "w.ts")
	if err := os.WriteFile(tsPath, []byte("console.log(1)\n"), 0o644); err != nil {
		t.Fatalf("write workload: %v", err)
	}
	w := Workload{Name: "w", Category: "compute", Path: tsPath}

	changed, err := EmitGolden(context.Background(), bento, w)
	if err != nil {
		t.Fatalf("EmitGolden first: %v", err)
	}
	if !changed {
		t.Fatal("first emit should have written the golden")
	}

	got, err := os.ReadFile(GoldenPath(w))
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	if string(got) != body {
		t.Fatalf("golden body = %q, want %q", got, body)
	}

	// The update-only rule: a rerun with the same output must not rewrite the file.
	changed, err = EmitGolden(context.Background(), bento, w)
	if err != nil {
		t.Fatalf("EmitGolden second: %v", err)
	}
	if changed {
		t.Fatal("second emit with identical output should not have written the golden")
	}
}

func TestEmitGoldenRewritesOnChange(t *testing.T) {
	work := t.TempDir()
	tsPath := filepath.Join(work, "w.ts")
	if err := os.WriteFile(tsPath, []byte("console.log(1)\n"), 0o644); err != nil {
		t.Fatalf("write workload: %v", err)
	}
	w := Workload{Name: "w", Category: "compute", Path: tsPath}
	golden := GoldenPath(w)
	if err := os.WriteFile(golden, []byte("stale\n"), 0o644); err != nil {
		t.Fatalf("seed golden: %v", err)
	}

	fresh := "// Code generated by bento test (commit none) from w.ts. DO NOT EDIT.\n\npackage main\n"
	changed, err := EmitGolden(context.Background(), stubBento(t, fresh), w)
	if err != nil {
		t.Fatalf("EmitGolden: %v", err)
	}
	if !changed {
		t.Fatal("emit over a differing golden should have rewritten it")
	}
	got, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("read golden: %v", err)
	}
	if string(got) != fresh {
		t.Fatalf("golden body = %q, want %q", got, fresh)
	}
}

func TestGoldenPathSwapsExtension(t *testing.T) {
	w := Workload{Name: "coercion", Category: "compute", Path: "workloads/compute/coercion.ts"}
	if got, want := GoldenPath(w), filepath.FromSlash("workloads/compute/coercion.golden"); got != want {
		t.Fatalf("GoldenPath = %q, want %q", got, want)
	}
}
